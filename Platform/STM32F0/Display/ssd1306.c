void LCD_Init(void)
{
   lcd_frame_valid = 0U;
   HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDRESS, comm, sizeof(comm),10);
}
//----------------------------------------------------------------------------------
void  LCD_command(uint8_t cmd)
{   
   uint8_t cmd_arr[2] = {0,0};
   cmd_arr[0] = COMMAND_MODE;
   cmd_arr[1] = cmd;
   HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDRESS, cmd_arr, sizeof(cmd_arr),10);
}
//----------------------------------------------------------------------------------
bool LCD_SetContrast(uint8_t contrast)
{
   uint8_t command[] = { COMMAND_MODE, 0x81U, contrast };
   return HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDRESS, command,
                                  sizeof(command), 10U) == HAL_OK;
}
//----------------------------------------------------------------------------------
void LCD_On(void)
{
   LCD_command(0xAF);
}
//----------------------------------------------------------------------------------
void LCD_Off(void)
{
   LCD_command(0xAE);
}
//----------------------------------------------------------------------------------
void LCD_Clear(void)
{
   for(uint16_t ix = 1; ix < BUFF_SIZE; ix++)
   {
      lcd_buff[ix] = 0;
   }
   x_cur = 0;
   y_cur = 0;
}
//----------------------------------------------------------------------------------
void LCD_Update(void)
{
   lcd_buff[0] = DATA_MODE;

   if (lcd_frame_valid == 0U)
   {
      /* Initialize every OLED page once; later frames send changed spans only. */
      uint8_t window[] = {
         COMMAND_MODE, 0x21, column_start, column_end,
         0x22, page_start, page_end
      };
      if ((HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDRESS, window,
                                   sizeof(window), 10U) == HAL_OK) &&
          (HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDRESS, lcd_buff,
                                   BUFF_SIZE, 50U) == HAL_OK))
      {
         memcpy(lcd_last_buff, &lcd_buff[1], BUFF_SIZE - 1U);
         lcd_frame_valid = 1U;
      }
      return;
   }

   for (uint8_t page = page_start; page <= page_end; ++page)
   {
      const uint16_t page_offset = (uint16_t)page * 128U;
      uint8_t first = 128U;
      uint8_t last = 0U;

      for (uint16_t column = 0U; column < 128U; ++column)
      {
         const uint16_t index = page_offset + column;
         if (lcd_buff[index + 1U] != lcd_last_buff[index])
         {
            if (first == 128U)
            {
               first = (uint8_t)column;
            }
            last = (uint8_t)column;
         }
      }

      if (first != 128U)
      {
         const uint8_t span_length = (uint8_t)(last - first + 1U);
         uint8_t window[] = {
            COMMAND_MODE, 0x21, first, last,
            0x22, page, page
         };

         lcd_page_tx[0] = DATA_MODE;
         memcpy(&lcd_page_tx[1],
                &lcd_buff[page_offset + first + 1U],
                span_length);

         if ((HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDRESS, window,
                                      sizeof(window), 10U) == HAL_OK) &&
             (HAL_I2C_Master_Transmit(&hi2c1, LCD_ADDRESS, lcd_page_tx,
                                      (uint16_t)span_length + 1U,
                                      50U) == HAL_OK))
         {
            memcpy(&lcd_last_buff[page_offset],
                   &lcd_buff[page_offset + 1U],
                   128U);
         }
      }
   }
}
//----------------------------------------------------------------------------------
void LCD_Chr(char ch)
{
   uint8_t i;
   uint8_t glyph;
   lcd_buff_idx=(y_cur*128 + x_cur*6) + 1;    
   if ((ch >= 0x20)&&(ch <= 0x7F)) glyph = (uint8_t)ch - 32U;
   else glyph = 95U;
   for (i = 0; i < 5; i++)
   {
        lcd_buff[lcd_buff_idx++] = font[glyph][i];
   }
   lcd_buff[lcd_buff_idx++] = 0x00;  
   x_cur++;
   if (x_cur > 20)
   {
      x_cur = 0;
      y_cur++;
      if (y_cur > 3)
      {
         y_cur = 0;
      }
   }
}
//----------------------------------------------------------------------------------
void LCD_2xChr(char ch)
{
   uint8_t i, c, glyph;
   uint8_t	b1, b2;  
   uint16_t	tmpIdx;
   
   lcd_buff_idx = (y_cur*128+x_cur*6)+1;
   tmpIdx = lcd_buff_idx-128;
   if ((ch >= 0x20)&&(ch <= 0x7F)) glyph = (uint8_t)ch - 32U;
   else glyph = 95U;
   
   for ( i = 0; i < 5; i++ ){
      c = font[glyph][i];
      b1  = (c&0x01)*3;
      b1 |= (c&0x02)*6;
      b1 |= (c&0x04)*12;
      b1 |= (c&0x08)*24;
      
      c >>= 4;
      b2  = (c&0x01)*3;
      b2 |= (c&0x02)*6;
      b2 |= (c&0x04)*12;
      b2 |= (c&0x08)*24;
      
      lcd_buff[tmpIdx++] = b1;
      lcd_buff[tmpIdx++] = b1;
      lcd_buff[tmpIdx+126] = b2;
      lcd_buff[tmpIdx+127] = b2;
   }
   lcd_buff_idx = (lcd_buff_idx + 11) % BUFF_SIZE;
   lcd_buff[lcd_buff_idx] = 0x00;    
   if(lcd_buff_idx == (BUFF_SIZE-1)) lcd_buff_idx = 1;
   else lcd_buff_idx++;
   x_cur = x_cur + 2;
   if (x_cur > 19){
      x_cur = 0;
      y_cur = y_cur + 2;
      if (y_cur > 3){
         y_cur = 0;
      }
   }
}
//----------------------------------------------------------------------------------
void LCD_FStr(const char *dataPtr, uint8_t x, uint8_t y)
{
   LCD_GotoXY(x,y);
   while(*dataPtr != 0)
   {
      LCD_Chr(*dataPtr);
      dataPtr++;
   }
}
//----------------------------------------------------------------------------------
void LCD_FScrollStr(const char *text,
                    uint8_t pixel_offset,
                    uint8_t page,
                    uint8_t width)
{
   if ((pixel_offset >= 6U) || (page > page_end) || (width > 128U))
   {
      return;
   }

   /* Offset spans six-pixel cells: five glyph columns plus one blank column. */
   const uint16_t page_offset = (uint16_t)page * 128U + 1U;
   for (uint16_t column = 0U; column < width; ++column)
   {
      const uint16_t source_pixel = column + pixel_offset;
      const uint16_t character_index = source_pixel / 6U;
      const uint8_t glyph_column = (uint8_t)(source_pixel % 6U);
      const char character = text[character_index];
      uint8_t pixel_data = 0U;

      if ((character != '\0') && (glyph_column < 5U))
      {
         const uint8_t glyph = ((character >= 0x20) && (character <= 0x7F))
                                   ? (uint8_t)character - 32U
                                   : 95U;
         pixel_data = font[glyph][glyph_column];
      }

      lcd_buff[page_offset + column] = pixel_data;
   }
}
////----------------------------------------------------
void LCD_2xFStr(const char *dataPtr, uint8_t x, uint8_t y)
{
   LCD_GotoXY(x,y);
   while(*dataPtr!=0)
   {
      LCD_2xChr(*dataPtr);
      dataPtr++;
   }
}
////----------------------------------------------------
void LCD_GotoXY(uint8_t x,uint8_t y)
{
   if((x < 21)&&(y < (page_end+1)))
   {
      x_cur = x;
      y_cur = y;
   }
}
