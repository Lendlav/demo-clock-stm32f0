////  This function adds a battery symbol to the lcd buffer
////----------------------------------------------------
void LCD_Batt(int val, uint8_t x, uint8_t y)
{   
   uint8_t bat_arr[] = { 0x1C, 0x1C, 0x7F, 0x41, 0x41, 0x41, 0x41, 
                    0x41, 0x41, 0x41, 0x41, 0x41, 0x41, 0x41, 
                    0x41, 0x41, 0x41, 0x41, 0x7F 
                  };
   const uint8_t battery_width = (uint8_t)sizeof(bat_arr);
   if ((x > 128U) || (x < battery_width) || (y > page_end))
   {
       return;
   }
   if (val < 3218) val = 3218;
   if (val > 4096) val = 4096;
   uint8_t fill_count = (uint8_t)(((val - 3218) * (battery_width - 3U)) / (4096 - 3218));
   for (uint8_t i = 0; i < fill_count; ++i)
   {
      bat_arr[battery_width - 1U - i] = 0x7F;
   }
   lcd_buff_idx = (uint16_t)(1U + (uint16_t)y * 128U + x - battery_width);
   for(uint8_t i = 0; i < battery_width; i++)
   {
      lcd_buff[lcd_buff_idx++]=bat_arr[i];
   }
}

static void lcd_set_pixel(uint8_t x, uint8_t y)
{
   const uint16_t index = (uint16_t)(1U + (uint16_t)(y / 8U) * 128U + x);
   lcd_buff[index] |= (uint8_t)(1U << (y % 8U));
}

/* Draw a row-major monochrome bitmap; zero bits leave the framebuffer unchanged. */
void LCD_DrawBitmap(const uint8_t *bitmap,
                    uint8_t width,
                    uint8_t height,
                    uint8_t row_stride,
                    int16_t x,
                    int16_t y)
{
   const uint16_t minimum_stride = (uint16_t)(((uint16_t)width + 7U) / 8U);

   if ((bitmap == NULL) || (width == 0U) || (height == 0U) ||
       (row_stride < minimum_stride))
   {
      return;
   }

   for (uint16_t source_y = 0U; source_y < height; ++source_y)
   {
      for (uint16_t source_x = 0U; source_x < width; ++source_x)
      {
         const uint16_t bitmap_index =
             (uint16_t)(source_y * row_stride + source_x / 8U);
         const uint8_t bitmap_mask = (uint8_t)(0x80U >> (source_x % 8U));

         if ((bitmap[bitmap_index] & bitmap_mask) != 0U)
         {
            const int32_t pixel_x = (int32_t)x + source_x;
            const int32_t pixel_y = (int32_t)y + source_y;

            if ((pixel_x >= 0) && (pixel_x < 128) &&
                (pixel_y >= 0) && (pixel_y < 32))
            {
               lcd_set_pixel((uint8_t)pixel_x, (uint8_t)pixel_y);
            }
         }
      }
   }
}

static void lcd_draw_line(int16_t x0, int16_t y0, int16_t x1, int16_t y1)
{
   const int16_t dx = (x1 >= x0) ? (x1 - x0) : (x0 - x1);
   const int16_t dy = (int16_t)-((y1 >= y0) ? (y1 - y0) : (y0 - y1));
   const int16_t step_x = (x0 < x1) ? 1 : -1;
   const int16_t step_y = (y0 < y1) ? 1 : -1;
   int16_t error = (int16_t)(dx + dy);

   for (;;) {
      if ((x0 >= 0) && (x0 < 128) && (y0 >= 0) && (y0 < 32)) {
         lcd_set_pixel((uint8_t)x0, (uint8_t)y0);
      }
      if ((x0 == x1) && (y0 == y1)) {
         break;
      }

      const int16_t doubled_error = (int16_t)(2 * error);
      if (doubled_error >= dy) {
         error = (int16_t)(error + dy);
         x0 = (int16_t)(x0 + step_x);
      }
      if (doubled_error <= dx) {
         error = (int16_t)(error + dx);
         y0 = (int16_t)(y0 + step_y);
      }
   }
}

